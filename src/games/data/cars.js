export function getRandomCar(difficultyFilter = null, usedIds = new Set()) {
  let pool = CAR_BRANDS;
  if (difficultyFilter && ['EASY', 'MEDIUM', 'HARD'].includes(difficultyFilter.toUpperCase())) {
    const filtered = CAR_BRANDS.filter((c) => c.difficulty === difficultyFilter.toUpperCase());
    if (filtered.length > 0) pool = filtered;
  }
  const unused = pool.filter((c) => !usedIds.has(c.id));
  const candidateList = unused.length > 0 ? unused : pool;
  const picked = candidateList[Math.floor(Math.random() * candidateList.length)];
  usedIds.add(picked.id);
  return picked;
}
