const MIN_TOTAL_LENGTH = 8;   // country code + very short national number
const MAX_E164_LENGTH = 15;

export class PhoneNumberError extends Error {
  constructor(message, code = 'INVALID_NUMBER') {
    super(message);
    this.name = 'PhoneNumberError';
    this.code = code;
  }
}

/** Unique, longest-first list of calling codes. */
const SORTED_CODES = [...new Set(COUNTRY_CALLING_CODES)].sort((a, b) => b.length - a.length || (a < b ? -1 : 1));

/**
 * Strip everything except digits and a single leading +.
 * Accepts: +234 801 234 5678, 234-801-234-5678, 2348012345678,
 * +2348012345678, (234) 801..., 00234..., etc.
 */
export function sanitizePhoneNumber(input) {
  if (typeof input !== 'string') throw new PhoneNumberError('Send the number as text ♡');
  let raw = input.trim();
  if (!raw) throw new PhoneNumberError('That number looks empty ♡');

  if (raw.startsWith('00')) raw = '+' + raw.slice(2); // international prefix

  const hasPlus = raw.startsWith('+');
  if (raw.slice(1).includes('+')) {
    throw new PhoneNumberError('There is an extra + in there ♡', 'BAD_FORMAT');
  }
  const digits = raw.replace(/\D/g, '');
  if (!digits) throw new PhoneNumberError('I could not find any digits in that ♡');
  return { digits, hasPlus };
}

function findCountryCode(digits) {
  for (const code of SORTED_CODES) {
    if (digits.startsWith(code)) return code;
  }
  return null;
}

/**
 * Normalize any supported user input into the exact digits-only,
 * country-code-first format required by plogme's requestPairingCode.
 *
 * Returns { e164, countryCode, national, formatted }
 * Throws PhoneNumberError with a friendly message when invalid.
 */
export function normalizeWhatsAppNumber(input) {
  const { digits, hasPlus } = sanitizePhoneNumber(input);
  const full = digits;

  if (!hasPlus) {
    // Without a + we only accept input that already starts with a known
    // country calling code — we never silently guess one.
    const code = findCountryCode(full);
    if (!code) {
      throw new PhoneNumberError(
        'I need the country code too ♡\nExample: +234 801 234 5678',
        'MISSING_COUNTRY_CODE'
      );
    }
  }

  if (full.length < MIN_TOTAL_LENGTH || full.length > MAX_E164_LENGTH) {
    throw new PhoneNumberError(
      `That number is ${full.length} digits — a real WhatsApp number is 8–15 digits including the country code ♡`,
      'BAD_LENGTH'
    );
  }

  const countryCode = findCountryCode(full);
  if (!countryCode) {
    throw new PhoneNumberError('I could not recognize that country code ♡', 'UNKNOWN_COUNTRY_CODE');
  }
  const national = full.slice(countryCode.length);
  if (national.length < 4 || national.length > MAX_E164_LENGTH - countryCode.length) {
    throw new PhoneNumberError('That national number looks too short or too long ♡', 'BAD_NATIONAL_LENGTH');
  }
  if (national.startsWith('0')) {
    throw new PhoneNumberError('Drop the leading 0 after the country code ♡ e.g. +234 801 234 5678', 'BAD_NATIONAL_START');
  }

  return { e164: full, countryCode, national, formatted: formatInternational(full) };
}

/** Pretty format: +234 801 234 5678 (groups of 3, best effort) */
export function formatInternational(e164) {
  const cc = findCountryCode(e164) ?? '';
  const rest = e164.slice(cc.length);
  const groups = [];
  for (let i = 0; i < rest.length; i += 3) groups.push(rest.slice(i, i + 3));
  return `+${cc} ${groups.join(' ')}`.trim();
}

/** True when the input normalizes to a plausible WhatsApp number. */
export function isValidWhatsAppNumber(input) {
  try {
    normalizeWhatsAppNumber(input);
    return true;
  } catch {
    return false;
  }
}
